#!/usr/bin/env node
// ─── coverage ────────────────────────────────────────────────────────────────
// Every CLI command must map to a real route, and must be exercised by the CLI
// e2e (scripts/cli-e2e.mjs) or the route sweep (scripts/test-handlers.mjs).
// Routes without a CLI command are listed (pages, SSE, login) so nothing is
// silently untested. Writes docs/COVERAGE.md; exits 1 on any problem.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

const routes = [];
for (const [file, re] of [['server.js', /\bapp\.(get|post|delete|put)\(\s*(?:ADMIN_PATH\s*\+\s*)?'([^']+)'/g], ['routes/solana.js', /\br\.(get|post|delete|put)\(\s*'([^']+)'/g]]) {
  for (const m of read(file).matchAll(re)) routes.push({ method: m[1].toUpperCase(), path: m[2], file });
}
for (const m of read('server.js').matchAll(/\bapp\.(get|post)\(\s*ADMIN_PATH\s*(?:\+\s*'([^']+)')?\s*,/g)) routes.push({ method: m[1].toUpperCase(), path: `/admin${m[2] || ''}`, file: 'server.js' });

const commands = [];
for (const m of read('cli.js').matchAll(/^def\('([a-z-]+)', '([^']*)', (.+)\);$/gm)) {
  const paths = [...m[3].matchAll(/\b(get|post|call)\(\s*(?:'(DELETE)',\s*)?[`'](\/(?:\$\{[^}]*\}|[^`'?$])*)/g)]
    .map((x) => ({ method: x[2] || x[1].toUpperCase(), path: x[3].replace(/\$\{[^}]*\}/g, 'X').replace(/\/$/, '') }));
  // `a.pos[0] ? get(A) : get(B)` style commands: keep every path they can hit.
  commands.push({ name: m[1], help: m[2], paths });
}

const e2e = read('scripts/cli-e2e.mjs');
const handlers = read('scripts/test-handlers.mjs');
const toRe = (p) => new RegExp(`^${p.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').replace(/:[a-zA-Z]+/g, '[^/]+')}$`);
const routeFor = (cp) => routes.find((r) => (r.method === cp.method || (cp.method === 'GET' && r.method === 'GET')) && toRe(r.path).test(cp.path.replace(/\$\{[^}]+\}/g, 'X')));

const problems = [];
const cmdRows = commands.map((c) => {
  const mapped = c.name === 'wait' ? ['GET /api/stats'] : c.paths.map((p) => { const r = routeFor(p); return r ? `${r.method} ${r.path}` : null; });
  if (mapped.some((x) => x === null) || !mapped.length) problems.push(`CLI command ${c.name} maps to a route that does not exist (${c.paths.map((p) => p.path).join(', ')})`);
  const exercised = new RegExp(`\\bcli\\(\\s*'${c.name}'`).test(e2e) || new RegExp(`\\bok\\(\\s*'${c.name}'`).test(e2e)
    || new RegExp(`\\['${c.name}'`).test(e2e) || new RegExp(`, '${c.name}'\\]`).test(e2e);
  if (!exercised) problems.push(`CLI command ${c.name} is not exercised by scripts/cli-e2e.mjs`);
  return { ...c, mapped, exercised };
});
const cliRoutes = new Set(cmdRows.flatMap((c) => c.mapped));
const routeRows = routes.map((r) => {
  const key = `${r.method} ${r.path}`;
  const lit = handlers.includes(`'${r.path}'`) || handlers.includes(`\`\${srv.base}${r.path}\``) || handlers.includes(`${r.path}'`) || new RegExp(r.path.replace(/:[a-zA-Z]+/g, '\\$\\{[A-Z_]+\\}').replace(/[.*+?^()|[\]\\]/g, '\\$&')).test(handlers);
  return { ...r, cli: cliRoutes.has(key), sweep: lit };
});
const untested = routeRows.filter((r) => !r.cli && !r.sweep);

const md = [
  '# Coverage',
  '',
  'Generated by `node scripts/coverage.mjs` — do not edit by hand.',
  '',
  `${routes.length} routes · ${commands.length} CLI commands · ${untested.length} routes reached only by the dashboards · **${problems.length} problems**`,
  '',
  '## CLI commands',
  '',
  '| Command | Route | Exercised by cli-e2e |',
  '|---|---|---|',
  ...cmdRows.map((c) => `| \`${c.name}\` | ${c.mapped.map((m) => `\`${m}\``).join(', ')} | ${c.exercised ? 'yes' : '**no**'} |`),
  '',
  '## Routes',
  '',
  '| Method | Path | CLI | Route sweep |',
  '|---|---|---|---|',
  ...routeRows.map((r) => `| ${r.method} | \`${r.path}\` | ${r.cli ? 'yes' : '—'} | ${r.sweep ? 'yes' : '—'} |`),
  '',
  ...(problems.length ? ['## Problems', '', ...problems.map((p) => `- ${p}`), ''] : []),
].join('\n');
writeFileSync(join(ROOT, 'docs', 'COVERAGE.md'), md + '\n');
console.log(`${routes.length} routes · ${commands.length} commands · ${untested.length} dashboard-only routes · ${problems.length} problems`);
for (const p of problems) console.log(`  - ${p}`);
if (untested.length) console.log(`  dashboard-only: ${untested.map((r) => `${r.method} ${r.path}`).join(', ')}`);
process.exit(problems.length ? 1 : 0);
